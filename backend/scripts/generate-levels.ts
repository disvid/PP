// Fills level slots 24-67 with procedurally generated scrambles of rising difficulty.
//   npm run generate:levels
// Deterministic (every level has a fixed seed), so re-running reproduces the same file. Writes:
//   ../frontend/src/data/generatedLevels.ts   boards, par and optimal line count (shipped to the browser)
//   ./generatedSolutions.ts                   one reference proof per level (server side only: used by verify and the bot)
import fs from "node:fs";
import path from "node:path";
import { boardToRows } from "../../frontend/src/data/levels";
import { generateBoards, GenOptions, moveToSource } from "../puzzleGenerator";

const FIRST_ID = 24;
const LAST_ID = 67;
const COUNT = LAST_ID - FIRST_ID + 1; // 44

const TIERS = [
  { name: "Shuffle", size: 3 as const, upTo: 12, colors: 3, arrows: [1, 2] as [number, number] },
  { name: "Scramble", size: 4 as const, upTo: 28, colors: 4, arrows: [2, 3] as [number, number] },
  { name: "Chaos", size: 5 as const, upTo: COUNT, colors: 5, arrows: [2, 4] as [number, number] },
];

interface Entry { tier: (typeof TIERS)[number]; optimal: number; row: Record<string, unknown>; solution: string }
const entries: Entry[] = [];
let tierStart = 0;

for (const tier of TIERS) {
  for (let i = tierStart; i < tier.upTo; i++) {
    const id = FIRST_ID + i;
    // difficulty ramps from a 3-move shortest proof up to a 10-move one across the 44 levels
    const wanted = 3 + Math.floor((i * 7) / (COUNT - 1));
    const options: GenOptions = { size: tier.size, ops: [wanted + 1, wanted + 3], colors: tier.colors, arrows: tier.arrows };

    let found = null;
    for (let attempt = 0; attempt < 800 && !found; attempt++) {
      const g = generateBoards(`proof-puzzle-level-${id}#${attempt}`, options);
      if (g && g.optimalLines >= wanted && g.optimalLines <= wanted + 2) found = g;
    }
    if (!found) throw new Error(`level ${id}: no puzzle with a ${wanted}-move proof found`);

    entries.push({
      tier,
      optimal: found.optimalLines,
      row: {
        size: tier.size,
        initial: boardToRows(found.initial),
        target: boardToRows(found.target),
        par: found.parLimit,
        optimal: found.optimalLines,
      },
      solution: found.solution.map(moveToSource).join("\n"),
    });
    console.log(`seed ${id} ${tier.size}x${tier.size}: proof ${found.optimalLines}`);
  }
  tierStart = tier.upTo;
}

// within a tier, easier puzzles first (stable for equal lengths), then number the levels 24..67
const rows: object[] = [];
const solutions: Record<number, string> = {};
let seq = 0;
for (const tier of TIERS) {
  const mine = entries.filter((e) => e.tier === tier).sort((a, b) => a.optimal - b.optimal);
  mine.forEach((e, n) => {
    const id = FIRST_ID + seq++;
    rows.push({
      id,
      title: `${tier.name} ${n + 1}`,
      description: `A freshly scrambled ${tier.size}x${tier.size} board. Swap, paint and rotate it back into the target. Repeating patterns are a hint that a helper could pay off.`,
      ...e.row,
    });
    solutions[id] = e.solution;
  });
}

const banner = "// AUTO-GENERATED by backend/scripts/generate-levels.ts (npm run generate:levels). Do not edit by hand.\n";

fs.writeFileSync(
  path.resolve(__dirname, "../../frontend/src/data/generatedLevels.ts"),
  `${banner}
export interface GeneratedLevel {
  id: number
  title: string
  description: string
  size: 3 | 4 | 5
  /** rows of block tokens, see parseGrid */
  initial: string[]
  target: string[]
  par: number
  optimal: number
}

export const GENERATED_LEVELS = ${JSON.stringify(rows, null, 2)} as GeneratedLevel[]
`,
);

fs.writeFileSync(
  path.resolve(__dirname, "../generatedSolutions.ts"),
  `${banner}
/** A shortest single-block proof for each generated level. */
export const GENERATED_SOLUTIONS: Record<number, string> = ${JSON.stringify(solutions, null, 2)}
`,
);
console.log(`wrote ${rows.length} levels`);
